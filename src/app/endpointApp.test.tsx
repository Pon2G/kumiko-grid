import { canvasPointToScreen, CELL_CANVAS_WIDTH, CELL_CANVAS_SCALE, CELL_CANVAS_PAD } from '../components/CellEditor/canvasHitResolver'

afterEach(() => { cleanup(); vi.restoreAllMocks(); viewport = defaultViewport; activePointers.clear() })
const defaultViewport = { width: CELL_CANVAS_WIDTH, height: TRIANGLE_HEIGHT * CELL_CANVAS_SCALE + CELL_CANVAS_PAD * 2, viewBoxHeight: TRIANGLE_HEIGHT * CELL_CANVAS_SCALE + CELL_CANVAS_PAD * 2 }
let viewport = defaultViewport
const activePointers = new Set<number>()
const pointA = { x: .5, y: 0 }
const pointB = { x: 0, y: TRIANGLE_HEIGHT }
const bottom = (fraction: number) => ({ x: fraction, y: TRIANGLE_HEIGHT })
const anchor = (name: string) => fireEvent.keyDown(within(screen.getByLabelText('正三角形セルエディター')).getByLabelText(name), { key: 'Enter' })
const draw = (start: string, end: string) => { anchor(start); anchor(end) }
const pointer = (type: string, point: { x: number; y: number }, id = 1, pointerType = 'mouse') => {
  if (type === 'pointerup' && !activePointers.has(id)) pointer('pointerdown', point, id, pointerType)
  if (type === 'pointerdown') activePointers.add(id)
  const canvas = screen.getByLabelText('正三角形セルエディター')
  vi.spyOn(canvas, 'getBoundingClientRect').mockReturnValue({ x: 0, y: 0, left: 0, top: 0, right: viewport.width, bottom: viewport.height, width: viewport.width, height: viewport.height, toJSON: () => ({}) })
  const position = canvasPointToScreen(point, viewport)
  const event = new Event(type, { bubbles: true })
  Object.defineProperties(event, { clientX: { value: position.x }, clientY: { value: position.y }, button: { value: 0 }, pointerId: { value: id }, pointerType: { value: pointerType }, isPrimary: { value: id === 1 } })
  fireEvent(canvas, event)
  if (type === 'pointerup') activePointers.delete(id)
}
const selectT = () => { pointer('pointerup', { x: -1, y: -1 }); pointer('pointerup', { x: .5, y: .25 }) }
const inspector = () => screen.getByLabelText('Segmentインスペクター')
const endpointInspector = () => screen.getByLabelText('端点編集インスペクター')
const endButton = () => within(inspector()).getByRole('button', { name: '終点を変更' })
const setup = async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: 'なし' }))
  draw('頂点A', 'BC辺を4等分した2番目の点')
  selectT()
  return user
}

